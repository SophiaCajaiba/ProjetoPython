#Declarar variáveis
comprimento = float(input("O comprimento do paralelepípedo é: "))
largura = float(input("A largura do paralelepípedo é: "))
altura = float(input("A altura do paralelepípedo é: "))

#Calcular o volume do paralelepípedo
volume = comprimento * largura * altura

#Mostrar o resultado
print("O volume do paralelepípedo é: ", volume)


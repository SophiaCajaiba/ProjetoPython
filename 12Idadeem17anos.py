#Declaração de variáveis
Ano_nascimento = int(input("Digite o ano de nascimento: "))
Ano_atual = int(input("Digite o ano atual: "))

#Calcular a idade em 17 anos
Idade_daqui_a_17_anos = (Ano_atual - Ano_nascimento) + 17

#Mostrar o resultado
print("A idade daqui a 17 anos será: ", Idade_daqui_a_17_anos)
